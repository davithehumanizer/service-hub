/**
 * Reference factors for the CO2e avoided by a repair.
 *
 * Source: The Restart Project, "Fixometer reference data" (2021), the LCA data
 * behind restarters.net — https://zenodo.org/records/5900046
 *
 * Their method, quoted from the workbook:
 *
 *     CO2e prevented (kg) = pre-use CO2e (kg) x displacement rate
 *
 * `preUseCo2eKg` is the average CO2e of manufacture and distribution for the
 * category. It replaces the previous `weight x constant` formula, which was
 * wrong in kind rather than in calibration: embodied carbon does not track
 * mass. That formula understated a mobile phone almost eightfold and
 * overstated a fan elevenfold.
 *
 * `products` is how many real products the average rests on, and it varies
 * enormously — twenty of these categories rest on one or two. Callers that
 * want to show a figure only when it means something should read it.
 */

/** Restart's central assumption: a repair displaces half a new manufacture. */
